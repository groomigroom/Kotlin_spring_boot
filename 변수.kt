fun main() {
    var a:Int = 122
    println(a)
    //122
    var b:Int? = null
    println(b)
    //null
    var c:Long = 123L
    println(c)
    //123
    var d:Double = 1.22
    println(d)
    //1.22
    var e:Float = 1.22f
    println(e)
    //1.22
    var f:Char = 'g'
    println(f)
    //g
    var g:Boolean = false
    println(g)
    //false
    var h = "김구름이 멍멍멍"
    println(h)
    //김구름이 멍멍멍
    var i = """김구름이
    멍멍멍
    멍멍"""
    println(i)
    /*
    김구름이
    멍멍멍
    멍멍
     * /
}
